// Command validationcatalog compiles the local reviewed planning inventory.
// It never fetches the external registry or creates executable runtime rules.
package main

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const inventoryVersion = "musicxml-validation-inventory-1"
const registryCommit = "3e33e4c80aa2a46ec323a5c2ea2c473e9f47905c"

// This is the SHA-256 of canonical JSON for the complete reviewed external
// snapshot metadata. It pins repository/upstream identities and verified file
// hashes independently of the editable source metadata. A pin migration must
// review and update both together; formatting-only JSON changes are harmless.
const snapshotSHA256 = "fa07120198f3d2c77e7a97cc515d19a4fbdbad56096b45b2e57891c2ebe6a950"

type object = map[string]any

func main() {
	plan := flag.String("plan", "docs/validation/plan", "committed local planning directory")
	output := flag.String("output", "validation/inventory/zz_generated_inventory.go", "generated Go source file")
	flag.Parse()
	data, err := generate(*plan)
	if err == nil {
		err = os.WriteFile(*output, data, 0644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "validation catalog:", err)
		os.Exit(1)
	}
}

func generate(planDir string) ([]byte, error) {
	// Reuse the complete independent checker before projection. In particular,
	// generic JSON unmarshaling must not normalize away duplicate object keys.
	// The module-local command validates relationships, reviewed digests, source
	// identity sets, support dispositions, and deferred inventory provenance.
	// No -registry option or network request is used.
	cmd, err := planningCommand(planDir)
	if err != nil {
		return nil, err
	}
	if out, err := cmd.CombinedOutput(); err != nil {
		return nil, fmt.Errorf("planning integrity: %w\n%s", err, out)
	}
	payload, err := project(planDir)
	if err != nil {
		return nil, err
	}
	canonical, err := json.Marshal(payload)
	if err != nil {
		return nil, err
	}
	var packed bytes.Buffer
	writer, err := gzip.NewWriterLevel(&packed, gzip.BestCompression)
	if err != nil {
		return nil, err
	}
	if _, err = writer.Write(canonical); err != nil {
		return nil, err
	}
	if err = writer.Close(); err != nil {
		return nil, err
	}
	encoded := base64.StdEncoding.EncodeToString(packed.Bytes())
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by internal/validationcatalog from committed planning JSON; DO NOT EDIT.")
	fmt.Fprintln(&source, "// Inspection-only provenance inventory; no executable MusicXML profile is supplied.")
	fmt.Fprintln(&source, "package inventory")
	fmt.Fprintf(&source, "\nconst musicXML40InventorySHA256 = %q\n", digest(canonical))
	fmt.Fprintln(&source, "\nconst musicXML40InventoryBase64 = \"\" +")
	for len(encoded) > 100 {
		fmt.Fprintf(&source, "\t%s +\n", strconv.Quote(encoded[:100]))
		encoded = encoded[100:]
	}
	fmt.Fprintf(&source, "\t%s\n", strconv.Quote(encoded))
	return format.Source(source.Bytes())
}

func project(planDir string) (object, error) {
	paths, err := filepath.Glob(filepath.Join(planDir, "*.json"))
	if err != nil {
		return nil, err
	}
	docs := map[string]object{}
	sourceFiles := []any{}
	var sourceManifest strings.Builder
	for _, path := range paths {
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		var doc object
		if err = json.Unmarshal(data, &doc); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		name := filepath.Base(path)
		docs[name] = doc
		sum := digest(data)
		sourceFiles = append(sourceFiles, object{"path": name, "bytes": len(data), "sha256": sum})
		sourceManifest.WriteString(name + "\x00" + sum + "\n")
	}
	snapshot := docs["external-snapshot.json"]
	snapshotBytes, err := json.Marshal(snapshot)
	if err != nil {
		return nil, err
	}
	if digest(snapshotBytes) != snapshotSHA256 {
		return nil, fmt.Errorf("external snapshot metadata differs from the independently pinned inventory; review migration explicitly")
	}
	if snapshot["registry_commit"] != registryCommit {
		return nil, fmt.Errorf("unexpected registry pin: review inventory migration explicitly")
	}
	catalogURL := snapshot["registry_repository"].(string) + "/blob/" + registryCommit + "/docs/validation/registry/catalog.json#"
	result := object{
		"version": inventoryVersion, "source_sha256": digest([]byte(sourceManifest.String())),
		"registry_repository": snapshot["registry_repository"], "registry_commit": registryCommit, "upstream_musicxml_commit": snapshot["upstream_musicxml_commit"],
		"external_files": snapshot["files"], "source_files": sourceFiles,
		"target_policies": docs["xsd-contracts.json"]["target_policies"], "dependency_semantics": docs["xsd-contracts.json"]["dependency_semantics"],
	}
	groups := []struct{ file, from, to, id, fields string }{
		{"prose-contracts.json", "overlap_reviews", "overlaps", "id", overlapFields},
		{"context-dispositions.json", "overlap_reviews", "overlaps", "id", overlapFields},
		{"advisory-clause-review.json", "advisory_clause_reviews", "advisory_reviews", "research_id", "research_id decision related_research_ids related_xsd_research_ids rationale normative_provenance reuse_check_ids primary_check_ids reuse_scope"},
		{"implementation-plan.json", "stages", "stages", "id", "id title depends_on acceptance dependency_interpretation scope_note"},
		{"open-questions.json", "open_questions", "questions", "id", "id registry_pointer description disposition proposed_interpretation hard_error_basis requirements contextual_research_ids closure"},

		{"research-map.json", "research_records", "records", "research_id", "research_id origin role disposition check_ids registry_pointer"},
		{"xsd-contracts.json", "instances", "instances", "id", "id revision research_id template_id role registry_pointer composition status stage reuse_instances diagnostic_policy plan_dependencies target_policy"},
		{"xsd-contracts.json", "checks", "checks", "id", checkFields},
		{"prose-contracts.json", "checks", "checks", "id", checkFields},
		{"context-dispositions.json", "checks", "checks", "id", checkFields},
		{"capabilities.json", "capability_gates", "capabilities", "id", "id label kind provider_status provider_requirement_ids check_ids targets closure missing_outcome"},
		{"implementation-plan.json", "requirements", "requirements", "id", "id title role inputs applicability targets dependencies normative_provenance test_contracts stage status acceptance source_bullets source_inventory research_ids"},
		{"context-dispositions.json", "dispositions", "contexts", "research_id", "research_id role disposition rationale produces dependencies closure translation"},
	}
	for _, name := range []string{"xsd-test-contracts.json", "prose-contracts.json", "context-dispositions.json", "implementation-plan.json"} {
		groups = append(groups, struct{ file, from, to, id, fields string }{name, "test_contracts", "tests", "id", "id check_ids requirement_ids targets status axis_status case_instantiation_gate"})
	}
	for _, group := range groups {
		rows, _ := result[group.to].([]any)
		for _, entry := range docs[group.file][group.from].([]any) {
			src := entry.(object)
			dst := object{}
			for _, key := range strings.Fields(group.fields) {
				if value, ok := src[key]; ok {
					dst[key] = value
				}
			}
			if pointer, ok := dst["registry_pointer"].(string); ok {
				dst["registry_url"] = catalogURL + pointer
				if group.to == "questions" {
					dst["registry_url"] = strings.TrimSuffix(catalogURL, "catalog.json#") + "issues.json#" + pointer
				}
			}
			if group.to == "checks" || group.to == "instances" {
				dst["runtime_support"] = "unsupported"
			}
			rows = append(rows, dst)
		}
		sort.Slice(rows, func(i, j int) bool { return rows[i].(object)[group.id].(string) < rows[j].(object)[group.id].(string) })
		result[group.to] = rows
	}
	return result, nil
}

const checkFields = "id research_ids revision role inputs selector targets capabilities dependencies dependency_modes normative_provenance test_contracts stage status closure readiness_gate capability_ids semantic_status implementation_binding model_limit model_evidence expected_outcomes research_clauses"

func digest(b []byte) string { sum := sha256.Sum256(b); return hex.EncodeToString(sum[:]) }

const overlapFields = "id research_id kind shared_condition additional_condition xsd_research_ids disposition justification additional_condition_check_ids additional_condition_source"

// planningCommand fixes the checker to this module's local source and explicitly
// disables dependency and toolchain downloads, even if the caller normally
// permits them. A generator binary outside a checkout fails rather than fetching.
func planningCommand(planDir string) (*exec.Cmd, error) {
	absolutePlan, err := filepath.Abs(planDir)
	if err != nil {
		return nil, err
	}
	root, err := os.Getwd()
	if err != nil {
		return nil, err
	}
	for {
		data, readErr := os.ReadFile(filepath.Join(root, "go.mod"))
		if readErr == nil {
			fields := strings.Fields(string(data))
			if len(fields) < 2 || fields[0] != "module" || fields[1] != "github.com/go-muse/go-musicxml" {
				return nil, fmt.Errorf("inventory generation requires the go-musicxml module checkout")
			}
			if info, statErr := os.Stat(filepath.Join(root, "internal", "validationplan", "main.go")); statErr != nil || !info.Mode().IsRegular() {
				return nil, fmt.Errorf("local planning checker is unavailable")
			}
			break
		}
		if !os.IsNotExist(readErr) {
			return nil, readErr
		}
		parent := filepath.Dir(root)
		if parent == root {
			return nil, fmt.Errorf("inventory generation requires the go-musicxml module checkout")
		}
		root = parent
	}
	cmd := exec.Command("go", "run", "./internal/validationplan", "-plan", absolutePlan)
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOPROXY=off", "GOSUMDB=off", "GOTOOLCHAIN=local")
	return cmd, nil
}
