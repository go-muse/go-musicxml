package xsdgen

import (
	"bytes"
	"encoding/xml"
	"strings"
)

// documentationWidth is the column at which generated comment text wraps.
const documentationWidth = 80

// SetDocumentationNotice makes generation from this index copy the schema's
// xs:documentation into Go comments, under notice. The notice, the
// attribution the schema's licence requires, heads every generated model file;
// without one no documentation is copied.
func (i *Index) SetDocumentationNotice(notice string) {
	i.documentationNotice = strings.TrimSpace(notice)
}

// documentation returns the documentation text of annotation when this index
// copies documentation, or "".
func (i *Index) documentation(annotation *Annotation) string {
	if i == nil || i.documentationNotice == "" || annotation == nil {
		return ""
	}
	var parts []string
	for _, entry := range annotation.Documentation {
		var text struct {
			Value string `xml:",chardata"`
		}
		if err := xml.Unmarshal([]byte("<d>"+entry.Content+"</d>"), &text); err != nil {
			continue
		}
		if value := strings.TrimSpace(text.Value); value != "" {
			parts = append(parts, value)
		}
	}
	return strings.Join(parts, "\n\n")
}

// writeGeneratedHeader starts a generated file: the generated-code marker
// and, when documentation is copied, the notice for it.
func writeGeneratedHeader(target *bytes.Buffer, index *Index) {
	target.WriteString("// Code generated by xsdgen; DO NOT EDIT.\n")
	if index != nil && index.documentationNotice != "" {
		target.WriteString("//\n")
		writeDocumentationBlocks(target, "", index.documentationNotice)
	}
	target.WriteString("\n")
}

// renderDocumentation appends text to the comment above a declaration, after
// its first sentence.
func renderDocumentation(target *bytes.Buffer, indent, text string) {
	if text == "" {
		return
	}
	target.WriteString(indent + "//\n")
	writeDocumentationBlocks(target, indent, text)
}

// renderFieldDocumentation writes text as the comment of a struct field.
func renderFieldDocumentation(target *bytes.Buffer, text string) {
	writeDocumentationBlocks(target, "\t", text)
}

// documentationBlock is a paragraph or one item of a list.
type documentationBlock struct {
	text string
	item bool
}

// documentationBlocks splits text at blank lines into paragraphs whose lines
// are joined with single spaces. An indented line, such as one value of a
// tab-indented list in the schema, becomes a list item of its own, so that
// indentation turns neither into a run-on paragraph nor into a code block.
func documentationBlocks(text string) []documentationBlock {
	var blocks []documentationBlock
	var current []string
	flush := func() {
		if len(current) != 0 {
			blocks = append(blocks, documentationBlock{text: strings.Join(current, " ")})
			current = nil
		}
	}
	for _, line := range strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n") {
		words := strings.Fields(line)
		switch {
		case len(words) == 0:
			flush()
		case line[0] == ' ' || line[0] == '\t':
			flush()
			blocks = append(blocks, documentationBlock{text: strings.Join(words, " "), item: true})
		default:
			current = append(current, strings.Join(words, " "))
		}
	}
	flush()
	return blocks
}

// writeDocumentationBlocks writes text as comment lines prefixed by indent, in
// the form gofmt keeps: wrapped paragraphs separated by blank comment lines,
// and list items as "  - " with indented continuation lines.
func writeDocumentationBlocks(target *bytes.Buffer, indent, text string) {
	width := documentationWidth - 3 - len(indent)*4
	blocks := documentationBlocks(text)
	for index, block := range blocks {
		// A list follows its introducing paragraph directly; a paragraph
		// after a paragraph or a list starts after a blank comment line.
		if index != 0 && !block.item {
			target.WriteString(indent + "//\n")
		}
		if !block.item {
			for _, line := range wrapDocumentation(block.text, width) {
				target.WriteString(indent + "// " + line + "\n")
			}
			continue
		}
		for position, line := range wrapDocumentation(block.text, width-4) {
			marker := "    "
			if position == 0 {
				marker = "  - "
			}
			target.WriteString(indent + "// " + marker + line + "\n")
		}
	}
}

// wrapDocumentation breaks paragraph into lines of at most width bytes where
// it can; a longer word keeps a line of its own.
func wrapDocumentation(paragraph string, width int) []string {
	var lines []string
	var line strings.Builder
	for _, word := range strings.Fields(paragraph) {
		if line.Len() != 0 && line.Len()+1+len(word) > width {
			lines = append(lines, line.String())
			line.Reset()
		}
		if line.Len() != 0 {
			line.WriteByte(' ')
		}
		line.WriteString(word)
	}
	if line.Len() != 0 {
		lines = append(lines, line.String())
	}
	return lines
}
