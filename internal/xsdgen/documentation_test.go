package xsdgen

import (
	"go/format"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const documentedSchema = `
<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema">
	<xs:simpleType name="state">
		<xs:annotation>
			<xs:documentation>The state type uses &lt;open&gt; &amp; closed values.

	An indented line
	joins its paragraph.</xs:documentation>
		</xs:annotation>
		<xs:restriction base="xs:token">
			<xs:enumeration value="open"/>
		</xs:restriction>
	</xs:simpleType>
	<xs:complexType name="box">
		<xs:annotation>
			<xs:documentation>A box holds one lid.</xs:documentation>
		</xs:annotation>
		<xs:sequence>
			<xs:element name="lid" type="xs:string">
				<xs:annotation>
					<xs:documentation>The lid closes the box.</xs:documentation>
				</xs:annotation>
			</xs:element>
		</xs:sequence>
	</xs:complexType>
</xs:schema>`

func documentedIndex(t *testing.T, notice string) *Index {
	t.Helper()
	index, err := NewIndex(&Set{Files: []*SchemaFile{parseSchemaFile(t, "types.xsd", documentedSchema)}})
	require.NoError(t, err)
	index.SetDocumentationNotice(notice)
	return index
}

func TestGenerateDocumentation(t *testing.T) {
	t.Parallel()

	index := documentedIndex(t, "Documentation is adapted from the Example 1.0 schema.")
	simple, err := GenerateSimpleTypes(index, "example")
	require.NoError(t, err)
	assert.True(t, strings.HasPrefix(string(simple), "// Code generated by xsdgen; DO NOT EDIT.\n//\n// Documentation is adapted from the Example 1.0 schema.\n\npackage example\n"), "%s", simple)
	assert.Contains(t, string(simple), `// State represents the "state" XSD simple type.
//
// The state type uses <open> & closed values.
//
// An indented line joins its paragraph.
type State string
`)

	complex, err := GenerateComplexTypes(index, "example")
	require.NoError(t, err)
	assert.Contains(t, string(complex), `// Box represents the "box" XSD complex type.
//
// A box holds one lid.
type Box struct {
	// The lid closes the box.
	Lid string `+"`"+`xml:"lid"`+"`"+`
}
`)
	for _, source := range [][]byte{simple, complex} {
		formatted, err := format.Source(source)
		require.NoError(t, err)
		assert.Equal(t, string(source), string(formatted), "documentation is stable under gofmt")
	}

	// Without a notice nothing is copied.
	plain, err := GenerateSimpleTypes(documentedIndex(t, ""), "example")
	require.NoError(t, err)
	assert.NotContains(t, string(plain), "closed values")
	assert.True(t, strings.HasPrefix(string(plain), "// Code generated by xsdgen; DO NOT EDIT.\n\npackage example\n"))
}

func TestWrapDocumentation(t *testing.T) {
	t.Parallel()

	assert.Equal(t, []string{"one two", "three"}, wrapDocumentation("one two three", 8))
	assert.Equal(t, []string{"a", "https://example.test/long/path", "b"}, wrapDocumentation("a https://example.test/long/path b", 10), "a long word keeps a line of its own")
	assert.Equal(t, []string{"first line joined", "second"}, documentationParagraphs("first\n\tline   joined\n \t\nsecond\r\n"))
	assert.Empty(t, documentationParagraphs(" \n\t\n"))
}
